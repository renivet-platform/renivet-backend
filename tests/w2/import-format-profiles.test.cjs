'use strict';

const assert = require('node:assert/strict');
const test = require('node:test');
const { detectImportFormatProfile, mapImportWorkbook } = require('../../dist/modules/imports/import-format-profiles.js');

const shopifyWorkbook = [
  { name: 'MASTER DATA', rows: [
    ['', '', 'Report generated by the seller workbook'],
    ['EAN', 'Shopify Handle', 'UNIQUE PRODUCT CODE', 'STYLE NAME', 'COLOR', 'SIZE', 'MRP', 'Inventory', 'Image Link', 'COMPOSITION'],
    ['8900000000012', 'demo-shirt-blue', 'DEMO-SHIRT-BLUE-M', 'Demo Shirt', 'Blue', 'M', 1499, 7, 'https://images.example/blue.jpg', 'Cotton'],
    ['8900000000029', 'demo-shirt-blue', 'DEMO-SHIRT-BLUE-L', 'Demo Shirt', 'Blue', 'L', 1499, '#N/A', 'https://images.example/blue-l.jpg', 'Cotton'],
  ] },
  { name: 'Cogs Data', rows: [['SEASON', 'STYLE NAME', 'COLOR', 'COGS', 'MRP'], ['SS26', 'Demo Shirt', 'Blue', 500, 1499]] },
];

const unicommerceWorkbook = [
  { name: 'START_HERE', rows: [['ILLUSTRATIVE TEMPLATE; not an official live export']] },
  { name: 'Uniware_API_Items', rows: [
    ['categoryCode', 'skuCode', 'name', 'color', 'size', 'brand', 'maxRetailPrice'],
    ['APPAREL', 'DEMO-TEE-BLUE-M', 'Demo Cotton Tee Blue M', 'Blue', 'M', 'Demo Brand', 1299],
  ] },
  { name: 'Inventory_Snapshot', rows: [
    ['facilityCode', 'itemTypeSKU', 'inventory', 'openSale', 'openPurchase'],
    ['BLR-01', 'DEMO-TEE-BLUE-M', 80, 8, 25],
    ['MUM-01', 'DEMO-TEE-BLUE-M', 25, 3, 5],
  ] },
];

test('REN2-76 recognizes the supplied Shopify workbook layout as a provisional versioned profile', () => {
  const profile = detectImportFormatProfile({ sourceKind: 'RENIVET_XLSX', sheets: shopifyWorkbook });
  assert.equal(profile.id, 'shopify-universal-xlsx-provisional');
  assert.equal(profile.version, '0.1.0');
  assert.equal(profile.provisional, true);
  const result = mapImportWorkbook({ profile, sheets: shopifyWorkbook });
  assert.equal(result.catalogRows.length, 2);
  assert.deepEqual(result.catalogRows[0], {
    sourceRecordKey: 'DEMO-SHIRT-BLUE-M',
    sourceProductKey: 'demo-shirt-blue',
    title: 'Demo Shirt',
    sku: 'DEMO-SHIRT-BLUE-M',
    options: { color: 'Blue', size: 'M' },
    attributes: { ean: '8900000000012', composition: 'Cotton' },
    sourceMrp: 1499,
    sourceImageUrl: 'https://images.example/blue.jpg',
  });
  assert.deepEqual(result.stockObservations, [{ sourceRecordKey: 'DEMO-SHIRT-BLUE-M', quantity: 7 }]);
  assert.equal(result.catalogRows[1].stockObservation, undefined, 'invalid inventory is not converted into a stock value');
});

test('REN2-76 maps Unicommerce item and facility stock sheets separately using a replaceable illustrative profile', () => {
  const profile = detectImportFormatProfile({ sourceKind: 'RENIVET_XLSX', sheets: unicommerceWorkbook });
  assert.equal(profile.id, 'unicommerce-comprehensive-xlsx-illustrative');
  assert.equal(profile.version, '0.1.0');
  assert.equal(profile.provisional, true);
  const result = mapImportWorkbook({ profile, sheets: unicommerceWorkbook });
  assert.equal(result.catalogRows.length, 1);
  assert.equal(result.catalogRows[0].sku, 'DEMO-TEE-BLUE-M');
  assert.equal(result.catalogRows[0].sourceProductKey, null, 'SKU-level API items do not prove a parent grouping key');
  assert.deepEqual(result.stockObservations, [
    { sourceRecordKey: 'DEMO-TEE-BLUE-M', locationKey: 'BLR-01', quantity: 80 },
    { sourceRecordKey: 'DEMO-TEE-BLUE-M', locationKey: 'MUM-01', quantity: 25 },
  ]);
  assert.equal(result.catalogRows[0].inventory, undefined, 'inventory never becomes a catalog write');
});

test('REN2-76 refuses an unrecognized workbook instead of guessing a profile', () => {
  assert.throws(() => detectImportFormatProfile({
    sourceKind: 'RENIVET_XLSX',
    sheets: [{ name: 'Sheet1', rows: [['SKU', 'Title'], ['A-1', 'Unknown']] }],
  }), { code: 'IMPORT_FORMAT_UNRECOGNIZED' });
});

test('REN2-76 isolates malformed product rows and rejects 5,001 catalog rows', () => {
  const malformed = [{ name: 'MASTER DATA', rows: [
    ['EAN', 'Shopify Handle', 'UNIQUE PRODUCT CODE', 'STYLE NAME'],
    ['', 'handle-without-key', '', 'Missing SKU'],
  ] }];
  const profile = detectImportFormatProfile({ sourceKind: 'RENIVET_XLSX', sheets: malformed });
  const result = mapImportWorkbook({ profile, sheets: malformed });
  assert.deepEqual(result.catalogRows, []);
  assert.deepEqual(result.rowErrors, [{ sourceRowNumber: 2, code: 'IMPORT_ROW_REQUIRED_FIELD' }]);

  const tooMany = [{ name: 'MASTER DATA', rows: [
    ['EAN', 'Shopify Handle', 'UNIQUE PRODUCT CODE', 'STYLE NAME'],
    ...Array.from({ length: 5_001 }, (_, i) => ['', 'same-handle', `SKU-${i}`, 'T-Shirt']),
  ] }];
  const tooManyProfile = detectImportFormatProfile({ sourceKind: 'RENIVET_XLSX', sheets: tooMany });
  assert.throws(() => mapImportWorkbook({ profile: tooManyProfile, sheets: tooMany }), { code: 'IMPORT_ROW_LIMIT_EXCEEDED' });
});
